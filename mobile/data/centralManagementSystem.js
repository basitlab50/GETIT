/**
 * Core Permission Evaluator (Backend / Service Layer & UI Gate)
 */
export function canStaffPerform(staff, moduleId, action = 'view', recordStateName = null) {
  if (!staff || staff.status !== 'active') return false;
  if (staff.roleTier === 'CEO') return true; // CEO has complete business visibility & executive authority

  const modPerms = staff.permissions?.[moduleId];
  if (!modPerms || !modPerms[action]) return false;

  // Enforce Territory Scoping for Regional/State Managers & Field Agents
  if (recordStateName && staff.territoryScope?.states && !staff.territoryScope.states.includes('ALL')) {
    const normalizedRecordState = String(recordStateName).toLowerCase();
    const matchesAllowedState = staff.territoryScope.states.some((st) =>
      normalizedRecordState.includes(st.toLowerCase()) ||
      st.toLowerCase().includes(normalizedRecordState)
    );
    if (!matchesAllowedState) return false;
  }

  return true;
}

/**
 * Returns only the dashboards that the logged-in staff member has permission to view
 */
export function getAuthorizedDashboardsForStaff(staff) {
  if (!staff || staff.status !== 'active') return [];
  return CENTRAL_DASHBOARD_MODULES.filter((mod) => canStaffPerform(staff, mod.id, 'view'));
}

/**
 * Generates an immutable, hash-chained audit entry for the Staff Activity & Accountability Centre
 */
export function buildImmutableAuditLog({
  staff,
  eventCategory = 'SYSTEM_CHANGE',
  actionType = 'EDIT',
  module = 'Central Management',
  targetEntity = 'Platform Record',
  previousValue = {},
  newValue = {},
  reason = 'Authorised staff action',
  approvedBy = null,
  previousHash = 'GENESIS',
}) {
  const nowStr = new Date().toISOString().replace('T', ' ').slice(0, 19);
  const rawDigest = `${nowStr}|${staff?.staffId || 'SYS'}|${actionType}|${module}|${targetEntity}|${JSON.stringify(newValue)}|${previousHash}`;
  let hashNum = 0;
  for (let i = 0; i < rawDigest.length; i++) {
    hashNum = (hashNum * 31 + rawDigest.charCodeAt(i)) >>> 0;
  }
  const integrityHash = `SHA256:${hashNum.toString(16).padStart(8, '0')}${Math.abs(hashNum ^ 0xa5a5a5a5).toString(16).padStart(8, '0')}`;

  return {
    id: `AUD-${Date.now().toString().slice(-6)}`,
    timestamp: nowStr,
    staffId: staff?.staffId || 'SYSTEM',
    staffName: staff?.fullName || 'Automated System',
    staffRole: staff?.position || 'System',
    department: staff?.department || 'Operations',
    territory: staff?.territoryScope?.states?.join(', ') || 'ALL',
    eventCategory,
    actionType,
    module,
    targetEntity,
    previousValue,
    newValue,
    reason,
    approvedBy: approvedBy || (staff?.roleTier === 'CEO' ? `${staff.staffId} (${staff.fullName})` : 'Direct Authorised Action'),
    deviceInfo: staff?.lastDevice || 'GETIT Central Management Portal',
    integrityHash,
  };
}
