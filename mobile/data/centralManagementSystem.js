// Helper to build a full permission map quickly
function makePermMap(config) {
  const result = {};
  CENTRAL_DASHBOARD_MODULES.forEach((mod) => {
    const acts = config[mod.id] || config.DEFAULT || [];
    result[mod.id] = {
      view: acts.includes('view'),
      create: acts.includes('create'),
      edit: acts.includes('edit'),
      approve: acts.includes('approve'),
      delete: acts.includes('delete'),
      export: acts.includes('export'),
      suspend: acts.includes('suspend'),
      manage: acts.includes('manage'),
    };
  });
  return result;
}

